import {mkdir,copyFile} from 'node:fs/promises';
import {fileURLToPath} from 'node:url';
const root=new URL('../',import.meta.url);
const copy=async(source,target)=>copyFile(new URL(source,root),new URL(target,root));
for(const directory of ['public/ocr/core/','public/ocr/lang/'])await mkdir(fileURLToPath(new URL(directory,root)),{recursive:true});
await copy('node_modules/tesseract.js/dist/worker.min.js','public/ocr/worker.min.js');
await copy('node_modules/tesseract.js/LICENSE.md','public/ocr/Tesseract-LICENSE.txt');
await copy('node_modules/tesseract.js-core/LICENSE','public/ocr/Tesseract-core-LICENSE.txt');
for(const variant of ['tesseract-core-lstm','tesseract-core-simd-lstm','tesseract-core-relaxedsimd-lstm'])for(const extension of ['wasm','wasm.js'])await copy(`node_modules/tesseract.js-core/${variant}.${extension}`,`public/ocr/core/${variant}.${extension}`);
await copy('node_modules/@tesseract.js-data/eng/4.0.0_best_int/eng.traineddata.gz','public/ocr/lang/eng.traineddata.gz');
